/**
 * Writes WebP variants of the memorization journey artwork.
 *
 * Run by hand and commit what it produces, like build-image-variants.mjs:
 *
 *    node scripts/build-hifz-art.mjs ../صور-رحلة-الحفظ/hifz-art
 *
 * The source folder holds the art under the names in the image brief —
 * `yahya-stand.png`, `fatima-wave.png`, `guest-cheer.png`, `map-1-oasis.jpg` and so on. The
 * sources are large (a character pose is ~2 MB of PNG) and stay out of the
 * repository; only the ladder below ships.
 *
 * Characters keep their transparency. Art that has not arrived yet is simply
 * absent from the generated index, and the app draws a placeholder for it.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { basename, dirname, extname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const publicDir = join(root, "client/public");
const source = process.argv[2];
if (!source || !existsSync(source)) {
  console.error("usage: node scripts/build-hifz-art.mjs <folder with the hifz art>");
  process.exit(1);
}

const CHARACTERS = ["yahya", "fatima", "guest"];
const POSES = ["stand", "avatar", "wave", "listen", "recite", "record", "think", "cheer", "point", "rest", "walk", "gift"];
const MAPS = ["map-1-oasis", "map-2-valley", "map-3-hills", "map-4-sky"];

/** stem → where it goes, which widths, and whether it has an alpha channel */
function plan(stem) {
  const [character, ...rest] = stem.split("-");
  const pose = rest.join("-");
  if (CHARACTERS.includes(character) && POSES.includes(pose)) {
    // An avatar is painted at 40-120 CSS px; a pose at up to ~420.
    const widths = pose === "avatar" ? [128, 256, 512] : [320, 640, 960];
    return { dir: `hifz-art/characters/${character}`, name: pose, widths, alpha: true };
  }
  // Badges, gift boxes and region treasures: square, painted at 48-200 CSS px.
  if (/^(rank-[1-5]|gift-(closed|open)|treasure-[1-4])$/.test(stem)) return { dir: "hifz-art/rewards", name: stem, widths: [128, 256, 512], alpha: true };
  // Surah icons, drawn at 34-90 CSS px in the list and on the map.
  if (/^surah-\d{3}$/.test(stem)) return { dir: "hifz-art/surahs", name: stem.slice(6), widths: [96, 192, 384], alpha: true };
  // Screen backgrounds: the tall ones fill a phone, the wide ones a desk or tablet.
  if (/^bg-(hifz-light|hifz-dark|review)$/.test(stem)) return { dir: "hifz-art/backgrounds", name: stem.slice(3), widths: [720, 1080, 1536], alpha: false };
  if (/^bg-(profiles|parent)$/.test(stem)) return { dir: "hifz-art/backgrounds", name: stem.slice(3), widths: [960, 1600, 2400], alpha: false };
  if (MAPS.includes(stem)) return { dir: "hifz-art/map", name: stem.slice(4), widths: [720, 1080, 1536], alpha: false };
  return null;
}

const index = {};
let written = 0, skipped = 0;
const unknown = [];
for (const file of readdirSync(source).sort()) {
  const ext = extname(file).toLowerCase();
  if (![".png", ".jpg", ".jpeg", ".webp"].includes(ext)) continue;
  const input = join(source, file);
  const target = plan(basename(file, extname(file)));
  if (!target) { unknown.push(file); continue; }

  const width = Number(execFileSync("magick", ["identify", "-format", "%w", `${input}[0]`]).toString());
  const widths = target.widths.filter(w => w <= width);
  if (widths.length === 0) widths.push(width);
  mkdirSync(join(publicDir, target.dir), { recursive: true });
  for (const w of widths) {
    const out = join(publicDir, target.dir, `${target.name}-${w}.webp`);
    if (existsSync(out) && statSync(out).mtimeMs > statSync(input).mtimeMs) { skipped++; continue; }
    const args = [input, "-resize", `${w}x`, "-quality", target.alpha ? "86" : "80", "-strip"];
    if (target.alpha) args.push("-define", "webp:alpha-quality=95", "-define", "webp:exact=false");
    execFileSync("magick", [...args, out]);
    written++;
  }
  const height = Number(execFileSync("magick", ["identify", "-format", "%h", `${input}[0]`]).toString());
  index[`/${target.dir}/${target.name}`] = { widths, ratio: Math.round((width / height) * 1000) / 1000 };
}

writeFileSync(join(root, "client/src/lib/hifz-art.generated.ts"),
`// Generated by scripts/build-hifz-art.mjs — do not edit.
// Key: the art's public path without width or extension.
export const hifzArt: Record<string, { widths: number[]; ratio: number }> = ${JSON.stringify(
  Object.fromEntries(Object.entries(index).sort(([a], [b]) => a.localeCompare(b))), null, 1)};
`);
console.log(`hifz art: ${written} written, ${skipped} current, ${Object.keys(index).length} indexed`);
if (unknown.length) console.log(`not in the brief, ignored: ${unknown.join(", ")}`);
