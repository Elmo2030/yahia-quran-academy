/**
 * Writes WebP variants of the story artwork.
 *
 * Run by hand — `node scripts/build-image-variants.mjs` — and commit what it
 * produces, the same arrangement as the hero images: the Cloudflare builder
 * has no image tooling, so the variants have to be in the repository.
 *
 * The source art is 1200-1600px wide and every card paints it at roughly
 * 380-570 CSS px, so a phone was downloading a 320 KB JPEG to fill a slot a
 * quarter of that size. Each source keeps its .jpg as the fallback for a
 * browser without WebP; the ladder below is what `srcset` picks from.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, statSync, existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, extname, basename } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const WIDTHS = [384, 640, 960, 1280, 1600];
const QUALITY = "82";

function* jpegs(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* jpegs(path);
    else if (extname(entry.name).toLowerCase() === ".jpg") yield path;
  }
}

let written = 0, skipped = 0;
const ladder = {};
for (const source of jpegs(join(root, "client/public/stories"))) {
  const width = Number(execFileSync("magick", ["identify", "-format", "%w", source]).toString());
  const stem = join(dirname(source), basename(source, ".jpg"));
  // No point writing a variant wider than the art itself.
  const targets = WIDTHS.filter(w => w <= width);
  for (const target of targets) {
    const out = `${stem}-${target}.webp`;
    if (existsSync(out) && statSync(out).mtimeMs > statSync(source).mtimeMs) { skipped++; continue; }
    execFileSync("magick", [source, "-resize", `${target}x`, "-quality", QUALITY, "-strip", out]);
    written++;
  }
  ladder[source.slice(join(root, "client/public").length)] = targets;
}

// The app reads this rather than guessing: art dropped in later has no
// variants yet, and a <source> pointing at a file that 404s does not fall back
// to the <img> — the picture would simply not appear. An unlisted image gets a
// plain <img> instead.
writeFileSync(join(root, "client/src/lib/story-image-widths.generated.ts"),
`// Generated by scripts/build-image-variants.mjs — do not edit.
export const storyImageWidths: Record<string, number[]> = ${JSON.stringify(
  Object.fromEntries(Object.entries(ladder).sort(([a], [b]) => a.localeCompare(b))), null, 1)};
`);
console.log(`image variants: ${written} written, ${skipped} already current, ${Object.keys(ladder).length} sources indexed`);
