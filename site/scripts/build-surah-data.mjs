// =============================================================================
// Split the two corpus files into one file per surah.
//
// The reader used to download the whole Quran (1.4 MB) and the whole
// transliteration (738 KB) to show one surah — half a megabyte over the wire to
// render seven ayahs of Al-Fatiha. Each surah now ships as its own file.
//
// The integrity checks the runtime used to make on every visit belong here
// instead: 114 surahs, 6236 ayahs, no empty text, a transliteration for every
// ayah. A corpus that fails any of these fails the build. What survives to the
// browser is a per-file check that the surah arrived whole, against the ayah
// counts written out below.
//
// The two corpus files live in site/data/ rather than client/public/, so they
// are the build's input and never part of what is deployed.
// =============================================================================

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const corpus = join(root, "data");
const outDir = join(root, "client/public/quran");

const TOTAL_SURAHS = 114;
const TOTAL_AYAHS = 6236;

const text = JSON.parse(readFileSync(join(corpus, "quran_text.json"), "utf8"));
const translit = JSON.parse(readFileSync(join(corpus, "quran_transliteration.json"), "utf8"));

const die = message => { console.error(`build-surah-data: ${message}`); process.exit(1); };

if (!translit?.surahs || Object.keys(translit.surahs).length !== TOTAL_SURAHS)
  die("the transliteration does not cover all 114 surahs");

// Group the flat "surah:ayah" keys.
const bySurah = new Map();
for (const [key, value] of Object.entries(text)) {
  const [surah, ayah] = key.split(":").map(Number);
  if (!Number.isInteger(surah) || !Number.isInteger(ayah)) die(`unreadable key ${key}`);
  if (typeof value !== "string" || !value.trim()) die(`empty ayah at ${key}`);
  if (!bySurah.has(surah)) bySurah.set(surah, new Map());
  bySurah.get(surah).set(ayah, value);
}
if (bySurah.size !== TOTAL_SURAHS) die(`the Quran text covers ${bySurah.size} surahs, not ${TOTAL_SURAHS}`);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const counts = [];
let written = 0;

for (let surah = 1; surah <= TOTAL_SURAHS; surah += 1) {
  const ayahs = bySurah.get(surah);
  if (!ayahs) die(`surah ${surah} is missing from the Quran text`);
  const romanized = translit.surahs[String(surah)];
  if (!romanized?.ayahs) die(`surah ${surah} is missing from the transliteration`);

  const numbers = [...ayahs.keys()].sort((a, b) => a - b);
  // Ayah numbers must run 1..n with no gap, or the reader would silently skip one.
  numbers.forEach((n, index) => { if (n !== index + 1) die(`surah ${surah} jumps to ayah ${n} at position ${index + 1}`); });

  const rows = numbers.map(number => {
    const r = romanized.ayahs[String(number)];
    if (typeof r !== "string" || !r.trim()) die(`no transliteration for ${surah}:${number}`);
    return { n: number, t: ayahs.get(number), r };
  });

  counts.push(rows.length);
  written += rows.length;
  writeFileSync(
    join(outDir, `surah-${String(surah).padStart(3, "0")}.json`),
    JSON.stringify({ s: surah, a: rows }),
  );
}

if (written !== TOTAL_AYAHS) die(`wrote ${written} ayahs, expected ${TOTAL_AYAHS}`);

// The basmalah the reader draws above every surah but Al-Fatiha and At-Tawbah,
// taken from the corpus rather than typed. Typing it by hand produced a string
// that looked identical and was not: the shadda and the fatha in the wrong
// order. Quranic text is copied, never retyped.
const basmalah = bySurah.get(1).get(1);
if (!basmalah.startsWith("بِ")) die("surah 1 ayah 1 is not the basmalah");

writeFileSync(
  join(root, "client/src/lib/surah-ayah-counts.generated.ts"),
  `// Generated by scripts/build-surah-data.mjs — do not edit.\n` +
  `// How many ayahs each surah must have, so a truncated file is caught in the\n` +
  `// browser rather than shown as a short surah.\n` +
  `/** The basmalah, exactly as the corpus spells it. */\n` +
  `export const BASMALAH = ${JSON.stringify(basmalah)};\n\n` +
  `export const ayahCounts: number[] = [\n` +
  counts.map((n, i) => `  ${n},${(i + 1) % 12 === 0 ? "\n" : ""}`).join("").replace(/\n\n/g, "\n") +
  `\n];\n`,
);

console.log(`build-surah-data: ${TOTAL_SURAHS} surahs, ${written} ayahs`);
