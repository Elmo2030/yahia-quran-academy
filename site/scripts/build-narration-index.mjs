/**
 * Lists which stories have a recorded narration, so a new recording only has
 * to be dropped into its folder — no code change per story.
 *
 *    node scripts/build-narration-index.mjs
 *
 * Runs as part of `pnpm build`; narration.test.ts fails if the committed
 * index has drifted from the folder, so a recording added without running it
 * is caught by the tests rather than silently missing a player.
 *
 * A new recording, from a WAV, to match the ones already there (mono, 24 kHz,
 * 64 kbps, about the same loudness):
 *
 *    ffmpeg -i in.wav -af "loudnorm=I=-11:TP=-1:LRA=11" -ar 24000 -ac 1 \
 *      -codec:a libmp3lame -b:a 64k <folder>/<slug>.mp3
 *
 * Where each kind of story goes (all under client/public/stories/):
 *    companions/audio/<slug>.mp3        e.g. companions/audio/ali.mp3
 *    audio/<chapter>/<slug>.mp3         e.g. audio/prophets/yusuf.mp3
 *    seerah/audio/<slug>.mp3            e.g. seerah/audio/<story slug>.mp3
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function narratedSlugs(folder) {
  try {
    return readdirSync(join(root, "client/public", folder))
      .filter(name => name.endsWith(".mp3"))
      .map(name => name.slice(0, -".mp3".length))
      .sort();
  } catch {
    return [];
  }
}

/** Prophet and nation stories live under a chapter: audio/<chapter>/<slug>.mp3. */
function narratedStories() {
  try {
    return readdirSync(join(root, "client/public/stories/audio"), { withFileTypes: true })
      .filter(entry => entry.isDirectory())
      .flatMap(entry => narratedSlugs(`stories/audio/${entry.name}`).map(slug => `${entry.name}/${slug}`))
      .sort();
  } catch {
    return [];
  }
}

export function renderIndex() {
  return `// Generated by scripts/build-narration-index.mjs — do not edit by hand.
export const narratedCompanions: readonly string[] = ${JSON.stringify(narratedSlugs("stories/companions/audio"))};
/** "<chapter>/<slug>", from client/public/stories/audio/<chapter>/<slug>.mp3 */
export const narratedStories: readonly string[] = ${JSON.stringify(narratedStories())};
export const narratedSeerah: readonly string[] = ${JSON.stringify(narratedSlugs("stories/seerah/audio"))};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, "client/src/lib/narration.generated.ts");
  writeFileSync(out, renderIndex());
  console.log("narration:", renderIndex().split("\n").filter(line => line.startsWith("export")).map(line => line.split(":")[0].replace("export const ", "") + " " + JSON.parse(line.split("= ")[1].replace(/;$/, "")).length).join(", "));
}
