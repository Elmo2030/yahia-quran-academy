/** A card's text in the requested language, falling back to the Arabic. */
export const aqeedahTextFor = (card: AqeedahCard, locale: "ar" | "en"): AqeedahText =>
  locale === "en" && card.en
    ? card.en
    : {
        title: card.title,
        value: card.value,
        story: card.story,
        didYouKnow: card.didYouKnow,
        valueName: card.valueName,
        thinkQuestion: card.thinkQuestion,
        challenge: card.challenge,
        artifact: card.artifact,
        badge: card.badge,
        source: card.source,
      };

export const aqeedahChapterOf = (card: AqeedahCard): AqeedahChapter =>
  aqeedahChapters.find(chapter => chapter.slug === card.chapter) ?? aqeedahChapters[0];
