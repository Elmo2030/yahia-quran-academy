// =============================================================================
// العقيدة — the creed section, as cards.
//
// Thirty-two cards in seven chapters, from the document Ahmed supplied. Each
// card is one idea: a story a child can picture, the ayah it rests on, a fact,
// a question to think about, a challenge, a keepsake, and the source it came
// from — the same shape the Seerah stories use, so the two sections read as one
// site.
//
// Arabic is the source text. `en` carries the translation where it exists;
// aqeedahTextFor falls back to the Arabic for anything not translated yet, so a
// missing translation shows the original rather than an empty card.
// =============================================================================

export type AqeedahChallenge = {
  type: "multiple_choice";
  question: string;
  options: string[];
  correctAnswer: number;
};

export type AqeedahText = {
  title: string;
  /** The one-line promise of the card. */
  value: string;
  story: string;
  didYouKnow: string;
  valueName: string;
  thinkQuestion: string;
  challenge: AqeedahChallenge;
  artifact: string;
  badge: string;
  source: { reference: string; note: string };
};

export type AqeedahCard = AqeedahText & {
  /** Some cards point at another section of the site; the document wrote these
   *  as a URL inside the prose. */
  more?: { label: string; href: string };
  slug: string;
  chapter: string;
  icon: string;
  /** Quran carries the same text in both languages — it is not translated. */
  ayah: { text: string; ref: string };
  reliability: string;
  en?: AqeedahText;
};

export type AqeedahChapter = {
  slug: string;
  titleAr: string;
  titleEn: string;
  descriptionAr: string;
  descriptionEn?: string;
};

